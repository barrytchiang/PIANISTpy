"""Write the settings tables of the manual from the package's declared fields.

    python docs/tools/settings_tables.py docs/reference/_settings_tables.rst

Also called by ``docs/conf.py`` at the start of every build, so the tables can
never lag the code: one table per group of `pianistpy.settings.FIELDS`, with
each field's name, its value in the default and the quick tier, and the one
line on what it controls. A quick value equal to the default is shown as
"same": the quick tier keeps a default until a cheaper value has passed the
tests.
"""

import sys
from pathlib import Path


def fmt(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, float):
        text = f"{value:.6g}"
        return text
    return str(value)


def render() -> str:
    from pianistpy.settings import FIELDS, GROUPS, TIERS

    out = []
    out.append(".. generated by docs/tools/settings_tables.py from pianistpy.settings; do not edit\n")
    for group in GROUPS:
        fields = FIELDS.get(group, {})
        if not fields:
            continue
        out.append(f"\n``{group}``\n{'-' * (len(group) + 4)}\n")
        out.append(
            ".. list-table::\n   :header-rows: 1\n   :widths: 26 14 14 46\n"
            "   :class: settings-table\n\n"
        )
        out.append("   * - Field\n     - Default\n     - Quick\n     - What it controls\n")
        for name, field in fields.items():
            default = fmt(field.value("default"))
            quick = field.value("quick")
            quick_text = "same" if field.quick is None else fmt(quick)
            doc = " ".join(field.doc.split())
            out.append(f"   * - ``{name}``\n     - {default}\n     - {quick_text}\n     - {doc}\n")
    out.append(
        "\nTiers: " + ", ".join(f"``{t}``" for t in TIERS) + ". A field is overridden one at a time, "
        "``pp.Settings(inversion={'n_nodes': 800})``; the result then records that it was made with custom "
        "settings and names the fields that differ.\n"
    )
    return "".join(out)


def write(target: str) -> int:
    path = Path(target)
    text = render()
    if not path.exists() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 2:
        print(__doc__)
        sys.exit(2)
    sys.exit(write(sys.argv[1]))
